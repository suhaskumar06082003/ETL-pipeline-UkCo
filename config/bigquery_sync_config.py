# client -> (tables in load order, BigQuery DDL file used to create missing tables)
# Ullas Nirantara: an older/smaller FieldAssist schema - no brand / production /
# finance tables, primary_order(_item) empty with different columns. The 10 tables
# it has, with the same specs; product without the brand join (brand_name = NULL).
ULSNIRT_TABLES = {
    t: FIELD_ASSIST_TABLES[t]
    for t in ("category", "salesman", "distributor", "outlet", "product", "beat", "beat_outlet",
              "invoice", "secondary_order", "secondary_order_item")
}
ULSNIRT_TABLES["product"] = {
    **FIELD_ASSIST_TABLES["product"],
    "select": [("CAST(NULL AS CHAR) AS brand_name" if c == "b.brand_name AS brand_name" else c)
               for c in FIELD_ASSIST_TABLES["product"]["select"]],
    "from": "product AS p",
}

BIGQUERY_PIPELINES = {
    "NATURO": {"tables": FIELD_ASSIST_TABLES, "ddl": "sql/bigqry/naturodb_tables.sql"},
    "HANGYO": {"tables": QCOM_TABLES, "ddl": "sql/bigqry/hangyodb_tables.sql"},
    # same FieldAssist schema as naturodb (all 19 specs checked against modernkitchendb)
    "MODERNKT": {"tables": FIELD_ASSIST_TABLES, "ddl": "sql/bigqry/modernkitchendb_tables.sql"},
    "ULSNIRT": {"tables": ULSNIRT_TABLES, "ddl": "sql/bigqry/ullasnirantaradb_tables.sql"},
}


def get_bigquery_pipeline(client_code: str) -> dict:
    code = str(client_code).upper()
    if code not in BIGQUERY_PIPELINES:
        raise KeyError(f"No BigQuery pipeline configured for {client_code!r}")
    return BIGQUERY_PIPELINES[code]
