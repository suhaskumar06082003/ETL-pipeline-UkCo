CREATE TABLE IF NOT EXISTS masterdb.`external_erp` (
  `erp_id` int NOT NULL COMMENT 'Surrogate PK',
  `rec_code` varchar(100) DEFAULT NULL COMMENT 'Human readable unique connector code',
  `erp_name` varchar(100) NOT NULL COMMENT 'Display name of the ERP',
  `company_name` varchar(150) NOT NULL COMMENT 'Legal entity owning the ERP',
  `description` text COMMENT 'Long description / notes',
  `config` json NOT NULL COMMENT 'Connector configuration (JSON blob)',
  `is_active` tinyint(1) NOT NULL DEFAULT '1' COMMENT 'Soft-switch: 1 = active',
  `created_by` int DEFAULT NULL COMMENT 'FK --> masterdb.muser.user_id that inserted the row',
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Insert TS',
  `updated_by` int DEFAULT NULL COMMENT 'FK --> masterdb.muser.user_id that last updated',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Last update TS',
  PRIMARY KEY (`erp_id`),
  KEY `idx_erp_rec_code` (`rec_code`),
  KEY `fk_erp_created_by` (`created_by`),
  KEY `fk_erp_updated_by` (`updated_by`),
  CONSTRAINT `fk_erp_created_by` FOREIGN KEY (`created_by`) REFERENCES `masterdb`.`muser` (`user_id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_erp_updated_by` FOREIGN KEY (`updated_by`) REFERENCES `masterdb`.`muser` (`user_id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='List of external ERPs integrated via staging';

