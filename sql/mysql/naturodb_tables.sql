-- 4.2  Warehouse
CREATE TABLE IF NOT EXISTS
  warehouse (
    warehouse_id INT UNSIGNED AUTO_INCREMENT COMMENT 'Surrogate PK',
    rec_code VARCHAR(100) COMMENT 'Human readable unique connector code Warehouse code',
    warehouse_name VARCHAR(255) NOT NULL COMMENT 'Display name',
    parent_warehouse_id INT UNSIGNED COMMENT 'Self-FK for nested storage',
    /* Address & geo */
    address_line1 VARCHAR(255) COMMENT 'Street address',
    city VARCHAR(100) COMMENT 'City',
    district VARCHAR(100) COMMENT 'District',
    state VARCHAR(100) COMMENT 'State / province',
    country VARCHAR(100) DEFAULT 'INDIA' COMMENT 'Country',
    pincode VARCHAR(10) COMMENT 'PIN / ZIP',
    latitude DECIMAL(19, 17) COMMENT 'GPS latitude',
    longitude DECIMAL(19, 17) COMMENT 'GPS longitude',
    contact_person VARCHAR(100) COMMENT 'Warehouse in-charge',
    contact_no VARCHAR(20) COMMENT 'Phone',
    alt_contact_no VARCHAR(20) COMMENT 'Backup phone',
    email VARCHAR(100) COMMENT 'Contact email',
    /* Operational */
    wh_type ENUM (
      'FULFILMENT',
      'DISTRIBUTION',
      'STORE',
      'CROSS_DOCK'
    ) NOT NULL DEFAULT 'FULFILMENT' COMMENT 'Functional type',
    capacity_cubic_m DECIMAL(18, 6) COMMENT 'Storage volume capacity (m³, 6 dp)',
    capacity_weight_kg DECIMAL(18, 6) COMMENT 'Weight capacity (kg, 6 dp)',
    service_region VARCHAR(100) COMMENT 'Primary service region',
    attributes_json JSON COMMENT 'Extra attributes (JSON)',
    /* Integration */
    client_id INT COMMENT 'FK --> mclient',
    ext_erp_id INT COMMENT 'FK --> external_erp',
    ext_erp_record_id VARCHAR(100) COMMENT 'Row ID in ERP',
    /* Audit */
    is_active TINYINT (1) NOT NULL DEFAULT 1 COMMENT 'Soft-switch',
    created_by INT COMMENT 'FK --> muser',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Insert TS',
    updated_by INT COMMENT 'FK --> muser',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Last update TS',
    is_deleted TINYINT (1) NOT NULL DEFAULT 0 COMMENT 'Soft delete flag',
    /* Indexes */
    INDEX idx_wh_rec_code (rec_code),
    INDEX idx_wh_name (warehouse_name),
    INDEX idx_wh_location (state, city),
    INDEX idx_wh_parent (parent_warehouse_id),
    INDEX idx_wh_client (client_id),
    INDEX idx_wh_ext_record (ext_erp_record_id),
    /* Foreign Keys */
    -- FK: parent_warehouse_id --> warehouse.warehouse_id
    CONSTRAINT fk_wh_parent FOREIGN KEY (parent_warehouse_id) REFERENCES warehouse (warehouse_id) ON DELETE SET NULL ON UPDATE CASCADE,
    -- FK: created_by --> masterdb.muser.user_id
    CONSTRAINT fk_wh_created_by FOREIGN KEY (created_by) REFERENCES masterdb.muser (user_id) ON DELETE SET NULL ON UPDATE CASCADE,
    -- FK: updated_by --> masterdb.muser.user_id
    CONSTRAINT fk_wh_updated_by FOREIGN KEY (updated_by) REFERENCES masterdb.muser (user_id) ON DELETE SET NULL ON UPDATE CASCADE,
    -- FK: client_id --> masterdb.mclient.client_id
    CONSTRAINT fk_wh_client FOREIGN KEY (client_id) REFERENCES masterdb.mclient (client_id) ON DELETE SET NULL ON UPDATE CASCADE,
    -- FK: ext_erp_id --> masterdb.external_erp.erp_id
    CONSTRAINT fk_wh_erp FOREIGN KEY (ext_erp_id) REFERENCES masterdb.external_erp (erp_id) ON DELETE RESTRICT ON UPDATE CASCADE,
    PRIMARY KEY (warehouse_id)
  ) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = 'Physical storage & fulfilment locations';

